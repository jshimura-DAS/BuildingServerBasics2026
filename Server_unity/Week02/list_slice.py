# list_slice.py
scores = [1200, 980, 1430, 1100, 1250, 900]
#  添字:     0     1     2     3     4    5

print(scores[0])      # 1200（先頭）
print(scores[-1])     # 900（末尾）

print(scores[1:4])    # [980, 1430, 1100]（1以上4未満）
print(scores[:3])     # [1200, 980, 1430]（先頭から3個）
print(scores[3:])     # [1100, 1250, 900]（3番目から最後まで）
print(scores[-3:])    # [1100, 1250, 900]（末尾から3個）
print(scores[::2])    # [1200, 1430, 1250]（1つおき）
print(scores[::-1])   # [900, 1250, 1100, 1430, 980, 1200]（逆順）